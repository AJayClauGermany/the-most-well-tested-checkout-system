package checkout.store;

import checkout.Receipt;
import checkout.orders.Order;
import checkout.orders.OrderIds;
import checkout.orders.OrderRepository;
import checkout.orders.Timestamps;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.time.Clock;
import java.util.Optional;
import java.util.OptionalInt;
import tools.jackson.databind.json.JsonMapper;

/**
 * An order repository backed by a SQL database, through plain JDBC ({@code java.sql}).
 *
 * <p>Orders live in one table, {@code orders}, with an auto-numbered {@code order_number} column
 * that becomes the order number, so ids are sequential and survive closing and reopening
 * the database. The receipt is stored as JSON text. The tests use
 * <a href="https://h2database.com/">H2</a>, an embedded database that needs no server:
 * {@code jdbc:h2:file:/some/folder/orders} or {@code jdbc:h2:mem:}.
 */
public final class JdbcOrderRepository implements OrderRepository, AutoCloseable {

    private static final JsonMapper JSON = JsonMapper.builder().build();

    private static final String CREATE_TABLE = """
            CREATE TABLE IF NOT EXISTS orders (
                order_number INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                created_at   VARCHAR(20) NOT NULL,
                receipt      CLOB NOT NULL
            )""";

    private final Connection connection;
    private final Clock clock;

    /**
     * Connects to the database and creates the {@code orders} table if it does not exist yet.
     *
     * @param jdbcUrl a JDBC URL, e.g. {@code "jdbc:h2:file:/tmp/orders"}
     * @param clock   the time source for {@code created_at}
     * @throws StorageException when the database cannot be opened
     */
    public JdbcOrderRepository(String jdbcUrl, Clock clock) {
        this(connect(jdbcUrl), clock);
    }

    /**
     * Uses a connection that is already open, and creates the {@code orders} table if it does
     * not exist yet. The repository owns the connection from now on: {@link #close()} closes it.
     *
     * <p>Handy for tests too: a mock {@code Connection} can simulate failures that a real
     * database hardly ever produces.
     *
     * @param connection an open database connection
     * @param clock      the time source for {@code created_at}
     * @throws StorageException when the table cannot be created
     */
    public JdbcOrderRepository(Connection connection, Clock clock) {
        this.connection = connection;
        this.clock = clock;
        try (Statement statement = connection.createStatement()) {
            statement.execute(CREATE_TABLE);
        } catch (SQLException e) {
            throw new StorageException("Could not create the orders table", e);
        }
    }

    private static Connection connect(String jdbcUrl) {
        try {
            return DriverManager.getConnection(jdbcUrl);
        } catch (SQLException e) {
            throw new StorageException("Could not open the database " + jdbcUrl, e);
        }
    }

    // "synchronized": one JDBC connection must not be used by two threads at the same time.
    @Override
    public synchronized String save(Receipt receipt) {
        // "?" placeholders keep the values apart from the SQL, so a receipt can never be
        // mistaken for a command (no SQL injection).
        String sql = "INSERT INTO orders (created_at, receipt) VALUES (?, ?)";
        try (PreparedStatement insert = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            insert.setString(1, Timestamps.now(clock));
            insert.setString(2, JSON.writeValueAsString(receipt));
            insert.executeUpdate();
            try (ResultSet keys = insert.getGeneratedKeys()) {
                keys.next();
                return OrderIds.of(keys.getInt(1));
            }
        } catch (SQLException e) {
            throw new StorageException("Could not save the order", e);
        }
    }

    @Override
    public synchronized Optional<Order> find(String id) {
        OptionalInt number = OrderIds.numberOf(id);
        if (number.isEmpty()) {
            return Optional.empty();
        }
        String sql = "SELECT created_at, receipt FROM orders WHERE order_number = ?";
        try (PreparedStatement select = connection.prepareStatement(sql)) {
            select.setInt(1, number.getAsInt());
            // Closing the statement also closes its result set (JDBC promises that).
            return orderFrom(id, select.executeQuery());
        } catch (SQLException e) {
            throw new StorageException("Could not look up " + id, e);
        }
    }

    /** The order in the result set's only row, or empty when the query found no row. */
    private static Optional<Order> orderFrom(String id, ResultSet row) throws SQLException {
        if (!row.next()) {
            return Optional.empty();
        }
        Receipt receipt = JSON.readValue(row.getString("receipt"), Receipt.class);
        return Optional.of(new Order(id, row.getString("created_at"), receipt));
    }

    /**
     * Closes the database connection. After this, {@link #save} and {@link #find} throw
     * {@link StorageException}.
     */
    @Override
    public synchronized void close() {
        try {
            connection.close();
        } catch (SQLException e) {
            throw new StorageException("Could not close the database", e);
        }
    }
}
